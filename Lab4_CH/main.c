void melody(const int notes[][2]){
    int i = 0;
    while (!((notes[i][0] == 0) && (notes[i][1] == 0))){
        defineDutyFreq(notes[i][0]);
        delay(notes[i][1]);
        i++;
    }
    defineDutyFreq(0);
}


